/**
 * Download path for the online editor and other callers.
 *
 * Mirrors the intent of email-template-workflows `zip-artifact`:
 * render one or more files, optionally build an index.html, and return a zip.
 *
 * This module only packages already-rendered content. Generation stays in
 * `@llazyemail/generate-template`.
 */
import archiver from 'archiver';

export function buildIndex(files, productName = 'files') {
  const rows = files
    .map(
      (f) =>
        `<li><a href="${escapeHtml(f.name)}">${escapeHtml(f.name)}</a></li>`,
    )
    .join('\n');
  return `<!DOCTYPE html>
<html>
<head><meta charset="utf-8"><title>${escapeHtml(productName)}</title></head>
<body>
  <h1>Rendered ${escapeHtml(productName)}</h1>
  <ul>
    ${rows}
  </ul>
  <p>Generated by generate-template-server. Compatible with the zip produced by
  <code>email-template-workflows</code> when <code>zip-artifact: true</code>.</p>
</body>
</html>`;
}

function escapeHtml(s) {
  return String(s)
    .replace(/&/g, '&')
    .replace(/</g, '<')
    .replace(/>/g, '>')
    .replace(/"/g, '"');
}

/**
 * Stream a zip of the given files to the response.
 * files: [{ name, content }]
 */
export function sendZip(res, files, artifactName = 'rendered', corsOrigin = '*') {
  const zipName = `${artifactName}.zip`;
  res.writeHead(200, {
    'content-type': 'application/zip',
    'content-disposition': `attachment; filename="${zipName}"`,
    'access-control-allow-origin': corsOrigin,
    'x-artifact-name': artifactName,
  });

  const archive = archiver('zip', { zlib: { level: 9 } });
  archive.on('error', (e) => {
    console.error(e);
    res.destroy(e);
  });
  archive.pipe(res);
  for (const f of files) {
    archive.append(f.content, { name: f.name });
  }
  archive.finalize();
}
